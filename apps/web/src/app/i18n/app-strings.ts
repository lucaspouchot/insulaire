/** The application's text, by language id. */
export const APP_STRINGS: Readonly<Record<string, StringTree>> = { en: EN, fr: FR };

/**
 * Flattens a nested tree into `a.b.c` keys — the same rule the Rust loader
 * applies to a locale file, so both sides agree on what a key is.
 */
export function flattenStrings(tree: StringTree, prefix = ''): Record<string, string> {
  const flat: Record<string, string> = {};
  for (const [segment, value] of Object.entries(tree)) {
    const key = prefix.length === 0 ? segment : `${prefix}.${segment}`;
    if (typeof value === 'string') {
      flat[key] = value;
    } else {
      Object.assign(flat, flattenStrings(value, key));
    }
  }
  return flat;
}
