/**
 * The application's own text, in every language it ships.
 *
 * The rule is absolute: **no string is written where it is displayed**. A
 * template names a key, and the key resolves here or in the project's locale
 * files (`docs/adr/ADR-0023-localised-content-keys.md`).
 *
 * These keys — the `ui.` namespace — are the *chrome*: the shell, the editor,
 * the play screen. They ship with the application so it is legible before any
 * content is loaded, and before the engine has started. A project may override
 * any of them by defining the same key in its own `ui` namespace; the content
 * wins, which is how a game renames "Play" without a code change.
 *
 * Everything the **game** says — menus, settings, dialogue — is content, and
 * belongs in `content/locales/`, not here.
 *
 * The shape is the same nested object a locale file uses, so the editor's
 * language screen can show application keys and content keys side by side.
 */

/** A nested tree of translations: the shape of a locale file. */
export interface StringTree {
  [segment: string]: string | StringTree;
}

